def _flatten(specs, depth=2):
    out = []
    for sp in specs:
        name = sp[0]
        if isinstance(name, tuple) and len(name) == 2 and name[0] == '@' and depth > 0:
            sub = M.get(name[1])
            if sub:
                inner = _flatten(sub, depth - 1)
                for (n, dx, dy, sc, rot) in inner:
                    out.append((n, sp[1] + dx * sp[3] * .8, sp[2] + dy * sp[3] * .8, sp[3] * sc * .8, rot))
                continue
        out.append(sp)
    return out

